"""Polyphase filter taps for the S5L8720 scaler: writes s5l8720-scaler-coef.h.

    python3 gen-s5l8720-scaler-coef.py > s5l8720-scaler-coef.h

The scaler has an 8-tap horizontal and a 4-tap vertical filter with 16
phases, of which the driver loads phases 0..8 (the hardware mirrors the
rest), taps in Q7 (a phase sums to 128, signed 9-bit fields).

Seven sets, chosen by the scale step (source pixels per output pixel):
set k serves steps up to LIMITS[k]. Each is a Lanczos-windowed sinc
low-pass over the filter's whole span,

    h(x) = sinc(fc * x) * sinc(x / a)       for |x| < a, else 0

with a = taps / 2 and the cutoff fc = 1 / step of the source's Nyquist rate.
The 8-tap filter is cut for the largest step of its set, so that no step
of the set aliases. Four taps are too few to hold that cut without
blurring the set's smaller steps, so the 4-tap filter is cut for the step
in the middle of its set's range. (Against a 32-lobe float resampler on
test signals at the steps the video player uses: on the long filter a cut
for the middle of the range is closer on average but loses fine detail to
aliasing at a set's largest step, which is where 640x360 on a 480x320
screen falls; on the short filter the middle of the range is the closest
outright. A Hann window was further off on both.) Set 0 (no shrinking) is
the plain Lanczos interpolator; its phase 0 is the identity.

Tap i of phase p is h((i - a) + p / 16): the output sample lies p/16 of a
pixel before tap a. Each phase is scaled to sum to 128 and rounded;
phases 0 and 8, which are symmetric, are rounded as mirror halves.
"""
import math

LIMITS = (1.0, 8 / 7, 4 / 3, 8 / 5, 2.0, 8 / 3, 4.0)
PHASES = 9
ONE = 128


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


def kernel(x, fc, a):
    return sinc(fc * x) * sinc(x / a) if abs(x) < a else 0.0


def to_q7(w):
    """Scale to sum ONE and round, the rounding error going to the taps
    whose fractions were furthest from their rounded values."""
    s = sum(w)
    w = [v * ONE / s for v in w]
    q = [math.floor(v + 0.5) for v in w]
    err = ONE - sum(q)
    order = sorted(range(len(w)), key=lambda i: (w[i] - q[i]) * (1 if err > 0 else -1),
                   reverse=True)
    for i in order[:abs(err)]:
        q[i] += 1 if err > 0 else -1
    return q


def phase_taps(taps, fc, p):
    a = taps // 2
    w = [kernel((i - a) + p / 16, fc, a) for i in range(taps)]
    if p == 0:
        # symmetric about tap a, tap 0 on the window's edge (zero)
        side = [w[a + j] for j in range(1, a)]
        s = w[a] + 2 * sum(side)
        side = [math.floor(v * ONE / s + 0.5) for v in side]
        return [0] + side[::-1] + [ONE - 2 * sum(side)] + side
    if p == PHASES - 1:
        # symmetric about the middle of the span: round one half to ONE / 2
        half = [v * (ONE // 2) / sum(w[:a]) for v in w[:a]]
        q = [math.floor(v + 0.5) for v in half]
        q[a - 1] += ONE // 2 - sum(q)
        return q + q[::-1]
    return to_q7(w)


def cutoff(taps, k):
    if k == 0:
        return 1.0
    if taps >= 8:
        return 1 / LIMITS[k]
    return 2 / (LIMITS[k - 1] + LIMITS[k])


def table(taps):
    return [[phase_taps(taps, cutoff(taps, k), p) for p in range(PHASES)]
            for k in range(len(LIMITS))]


def emit(name, taps):
    out = ["static const s16 %s[%d][%d][%d] = {" % (name, len(LIMITS), PHASES, taps)]
    for st in table(taps):
        out.append("\t{")
        for ph in st:
            assert sum(ph) == ONE and all(-256 <= v < 256 for v in ph)
            out.append("\t\t{ " + ", ".join("%4d" % v for v in ph) + " },")
        out.append("\t},")
    out.append("};")
    return "\n".join(out)


HEADER = """/* SPDX-License-Identifier: GPL-2.0-only */
/*
 * Polyphase filter taps of the S5L8720 scaler. Generated by
 * gen-s5l8720-scaler-coef.py: do not edit.
 *
 * Seven sets, sharpest first: set 0 for 1:1 and enlarging, sets 1-6 for
 * shrinking by up to 8:7, 4:3, 8:5, 2:1, 8:3 and 4:1. Each is a
 * Lanczos-windowed sinc over the filter's span: 8 taps across, cut for the
 * set's largest shrink, and 4 down, cut for the middle of the set's range.
 * 16 phases, of which 0..8 are written (the rest are their mirrors), Q7 (a
 * phase sums to 128).
 */
#ifndef S5L8720_SCALER_COEF_H
#define S5L8720_SCALER_COEF_H

#include <linux/types.h>
"""

if __name__ == "__main__":
    assert table(8)[0][0] == [0, 0, 0, 0, ONE, 0, 0, 0]
    assert table(4)[0][0] == [0, 0, ONE, 0]
    print(HEADER)
    print(emit("s5l_scaler_h8", 8))
    print()
    print(emit("s5l_scaler_v4", 4))
    print()
    print("#endif")
