"""Polyphase filter taps of the N72 CLCD video layer: writes n72-clcd-coef.h.

    python3 gen-n72-clcd-coef.py > n72-clcd-coef.h

The video layer's scaler is the same kind of filter as the S5L8720 m2m
scaler, so the taps come from that block's generator
(drivers/media/platform/apple/gen-s5l8720-scaler-coef.py, whose docstring
has the reasoning): Lanczos-windowed sinc over the filter's span, the
identity set the plain interpolator, phases 0 and 8 rounded as mirror
halves, every phase summing to 128.

The cut-offs follow the scaler's rule as well: the 8-tap filter is cut for
the largest step of its set, so that no step of the set aliases, the
4-tap one for the step in the middle of its set's range. Against a
32-lobe float reference resampler, at the steps a video player produces
(scaling 640x360, 426x240, 854x480, 720x576 and 720x480 sources to 480x320;
a 1-D host model since this layer's output cannot be read back from the
hardware): the 8-tap taps are +0.59 dB on average and worse in one place
only (set 1 at a step of 2.67, -0.5 to -0.7 dB). Cut for the middle of the
range they would average +1.29 dB but lose fine stripes to aliasing at the
top of sets 6 and 5 (-2.9 dB at 1.125, -1.8 dB at 4:3, which is 640x360 at
full width). The
4-tap taps are +0.39 dB (luma) and +0.73 dB (chroma) on average, with fine
stripes -1.0 dB at 1.125 and -0.5 dB at 2.25.

What differs is the layout the CLCD takes:

  - a u32 holds two taps as signed 12-bit fields, the first tap in bits
    27:16 and the second in bits 11:0; a phase is 8 taps (4 words) or 4
    taps (2 words), phases 0..8 of 16 in order (the hardware mirrors the
    rest), 36 and 18 words a set;
  - taps run the other way round: the centre is tap 3 of 8 (1 of 4) and the
    zero tap of phase 0 is the last, so each phase is the scaler's reversed;
  - eight sets, blurriest first. n72_v_pick() picks set k for a step
    (source pixels per output pixel) in (TOP[k + 1], TOP[k]]:

        set 7: up to 1:1   6: 8:7   5: 4:3   4: 8:5   3: 2:1   2: 8:3
        set 1: 4:1 (n72_v_check() allows no more)
        set 0: beyond 4:1 down, never reached; a copy of set 1

    The 4-tap table is also indexed by n72_v_pick()'s second choice, which
    only ever names sets 7, 5, 3 (and 0): those sets do double duty there,
    presumably for the chroma planes at half the step.
"""
import importlib.util
import os

_here = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location(
    "s5l_coef", os.path.join(_here, "../../../media/platform/apple/gen-s5l8720-scaler-coef.py"))
s5l = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(s5l)

ONE = s5l.ONE
PHASES = s5l.PHASES
SETS = 8
# set k serves steps up to TOP[k]; the scaler's LIMITS, blurriest first
TOP = (4.0,) + tuple(reversed(s5l.LIMITS))


def cutoff(taps, k):
    """8 taps: for the largest step of CLCD set k; 4 taps: for the middle of
    its range of steps. Set 0 is set 1's copy."""
    k = max(k, 1)
    if k == SETS - 1:
        return 1.0
    if taps >= 8:
        return 1 / TOP[k]
    return 2 / (TOP[k] + TOP[k + 1])


def table(taps):
    return [[s5l.phase_taps(taps, cutoff(taps, k), p)[::-1] for p in range(PHASES)]
            for k in range(SETS)]


def pack(ph):
    assert all(-2048 <= v < 2048 for v in ph)
    return [(ph[i] & 0xfff) << 16 | (ph[i + 1] & 0xfff) for i in range(0, len(ph), 2)]


def check(taps, t):
    centre = taps // 2 - 1
    for k, st in enumerate(t):
        assert len(st) == PHASES
        for ph in st:
            assert len(ph) == taps and sum(ph) == ONE
            assert all(-2048 <= v < 2048 for v in ph)
        # phase 8 is half way between taps centre and centre + 1
        assert st[PHASES - 1] == st[PHASES - 1][::-1]
        # phase 0 is symmetric about the centre tap
        assert st[0][:centre] == st[0][centre + 1:2 * centre + 1][::-1]
    ident = [0] * taps
    ident[centre] = ONE
    assert t[SETS - 1][0] == ident
    assert t[0] == t[1]


def emit(name, taps):
    t = table(taps)
    check(taps, t)
    words = PHASES * taps // 2
    out = ["static const u32 %s[%d][%d] = {" % (name, SETS, words)]
    for k, st in enumerate(t):
        out.append("\t{\t/* set %d: %s */" % (k, "copy of set 1" if k == 0 else
                                             "steps up to %.4g" % TOP[k]))
        for p, ph in enumerate(st):
            w = pack(ph)
            out.append("\t\t" + ", ".join("0x%08x" % v for v in w) + ",\t/* %s */" %
                       " ".join("%d" % v for v in ph))
        out.append("\t},")
    out.append("};")
    return "\n".join(out)


HEADER = """/* SPDX-License-Identifier: GPL-2.0-only */
/*
 * Polyphase filter taps of the N72 CLCD video layer. Generated by
 * gen-n72-clcd-coef.py (python3 gen-n72-clcd-coef.py > n72-clcd-coef.h):
 * do not edit.
 *
 * Eight sets, blurriest first, picked by n72_v_pick(): set 7 for 1:1 and
 * enlarging, sets 6-1 for shrinking by up to 8:7, 4:3, 8:5, 2:1, 8:3 and
 * 4:1, set 0 (never reached) a copy of set 1. Lanczos-windowed sinc as for
 * the S5L8720 scaler: 8 taps cut for the set's largest shrink, 4 taps for
 * the middle of the set's range.
 * Phases 0..8 of 16, Q7 (a phase sums to 128), two signed 12-bit taps a
 * word, the first in the upper half.
 */
#ifndef N72_CLCD_COEF_H
#define N72_CLCD_COEF_H

#include <linux/types.h>
"""

if __name__ == "__main__":
    print(HEADER)
    print(emit("n72_v_h8", 8))
    print()
    print(emit("n72_v_t4", 4))
    print()
    print("#endif")
